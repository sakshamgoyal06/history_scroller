/**
 * Builds supabase/seed.sql from the content that ships in the app today (BUILD_PLAN M0.2).
 *
 * Publishing rule (PRD §5, §10.3a): only items that carry sources are seeded as `published`.
 * Catalog cards and reel posts have no per-item sources yet, so they go in as `review` until an
 * editor adds sources; the UPSC sample edition stays in `review` because it is sample content.
 * Learning Zone decks are cited card by card, so complete chapters are published.
 */
import { ADDITIONAL_LEARNING_CARDS } from '../src/catalog/data/additionalCards.js'
import { CORE_CARDS } from '../src/catalog/data/coreCards.js'
import { PROTOTYPE_FEED_ITEMS } from '../src/feed/prototypeFeedItems.js'
import { SUBJECTS, chapterProblems, isChapterReady } from '../src/upsc/learningZone.js'
import { UPSC_EXPLAINERS, UPSC_SAMPLE_POSTS } from '../src/upsc/upscContent.js'
import { LEARNING_ZONES } from '../src/zones/zoneData.js'

const lit = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replaceAll("'", "''")}'`)
const json = (v) => `${lit(JSON.stringify(v))}::jsonb`
const arr = (xs) => `array[${xs.map(lit).join(', ')}]::text[]`

function contentRow(r) {
  return `(${[
    lit(r.id),
    lit(r.type),
    arr(r.modePool),
    lit(r.domain ?? null),
    arr(r.topics ?? []),
    arr(r.gs ?? []),
    lit(r.eventDate ?? null),
    json(r.body),
    json(r.sources ?? []),
    lit(r.status),
    r.status === 'published' ? 'now()' : 'null',
  ].join(', ')})`
}

/** @returns {{ sql: string, counts: Record<string, number> }} */
export function buildSeedSql() {
  const content = []
  for (const card of [...CORE_CARDS, ...ADDITIONAL_LEARNING_CARDS]) {
    content.push({ id: card.id, type: 'card', modePool: ['curious'], domain: card.category, body: card, status: 'review' })
  }
  for (const item of PROTOTYPE_FEED_ITEMS) {
    content.push({ id: item.id, type: 'post', modePool: ['curious'], domain: item.domain, topics: item.topics, body: item, status: 'review' })
  }
  for (const post of UPSC_SAMPLE_POSTS) {
    content.push({
      id: post.id,
      type: 'ca_post',
      modePool: ['upsc'],
      gs: [post.gs],
      eventDate: post.dateKey,
      body: post,
      sources: post.sources,
      status: 'review',
    })
  }
  for (const [id, exp] of Object.entries(UPSC_EXPLAINERS)) {
    content.push({ id: `exp:${id}`, type: 'explainer', modePool: ['upsc'], gs: [exp.gs], body: exp, sources: exp.sources ?? [], status: 'review' })
  }

  const subjects = []
  const chapters = []
  SUBJECTS.forEach((subject, si) => {
    subjects.push(`(${[lit(subject.id), lit(subject.name), lit(subject.gs), si].join(', ')})`)
    subject.chapters.forEach((ch, ci) => {
      const ready = isChapterReady(ch) && chapterProblems(ch).length === 0
      const cardIds = (ch.cards ?? []).map((_, i) => `${ch.id}#${i}`)
      ;(ch.cards ?? []).forEach((card, i) =>
        content.push({
          id: `${ch.id}#${i}`,
          type: 'chapter_card',
          modePool: ['upsc'],
          domain: subject.name,
          gs: [subject.gs],
          body: card,
          sources: [{ title: card.cite }],
          status: ready ? 'published' : 'draft',
        }),
      )
      chapters.push(
        `(${[lit(ch.id), lit(subject.id), lit(ch.title), ci, lit(ch.summary ?? null), ch.video ? json(ch.video) : 'null', arr(cardIds), lit(ready ? 'published' : 'draft')].join(', ')})`,
      )
    })
  })

  const zones = LEARNING_ZONES.map((z) => `(${[lit(z.id), lit(z.title), arr(z.steps.map((s) => s.cardId)), lit('draft')].join(', ')})`)

  const sql = [
    '-- Generated by `npm run db:seed:build` (scripts/seedSql.js). Do not edit by hand.',
    'begin;',
    'insert into public.content_items (id, type, mode_pool, domain, topics, gs_tags, event_date, body, sources, status, published_at) values',
    content.map(contentRow).join(',\n') + '\non conflict (id) do update set body = excluded.body, sources = excluded.sources, status = excluded.status, published_at = excluded.published_at;',
    'insert into public.subjects (id, name, gs, position) values',
    subjects.join(',\n') + '\non conflict (id) do update set name = excluded.name, gs = excluded.gs, position = excluded.position;',
    'insert into public.chapters (id, subject_id, title, position, summary, video, card_ids, status) values',
    chapters.join(',\n') +
      '\non conflict (id) do update set title = excluded.title, position = excluded.position, summary = excluded.summary, video = excluded.video, card_ids = excluded.card_ids, status = excluded.status;',
    'insert into public.zones (id, title, item_ids, status) values',
    zones.join(',\n') + '\non conflict (id) do update set title = excluded.title, item_ids = excluded.item_ids;',
    'commit;',
    '',
  ].join('\n')

  const counts = {
    content: content.length,
    published: content.filter((c) => c.status === 'published').length,
    chapters: chapters.length,
    zones: zones.length,
  }
  return { sql, counts }
}
